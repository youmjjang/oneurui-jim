import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const js=readFileSync(new URL('./dist/app.js',import.meta.url),'utf8');
const html=readFileSync(new URL('./dist/index.html',import.meta.url),'utf8');
const logic=js.slice(0,js.indexOf('function sortedResults'));
const ctx=vm.createContext({document:{},localStorage:{getItem:()=>null},Intl,Date});
vm.runInContext(logic,ctx);
const run=code=>vm.runInContext(code,ctx);
assert.equal(run("travel('seoul','seoul').minutes"),0);
assert.equal(run("travel('seoul','city').minutes"),5);
assert.equal(run("travel('city','seoul').minutes"),5);
run("globalThis.q={start:'seoul',visit:'seongsu',end:'hongdae',size:'M',mode:'route',priority:'total',deposit:new Date('2026-10-20T13:00'),pickup:new Date('2026-10-20T17:00')}");
assert.equal(run('validate(q)'), '');
assert.equal(run('calculate(q).length'),6);
assert.equal(run("calculate({...q,size:'L'}).some(l=>l.id==='l2')"),false);
assert.equal(run("calculate({...q,pickup:new Date('2026-10-20T23:30')}).some(l=>l.id==='l4')"),false);
assert.ok(run("validate({...q,pickup:q.deposit}).length")>0);
assert.ok(run("validate({...q,pickup:new Date('bad')}).length")>0);
assert.equal(run("quote(LOCKERS[0],q)"),3500);
assert.equal(run("quote(LOCKERS[0],{...q,pickup:new Date('2026-10-20T17:01')})"),4400);
assert.ok(run("calculate(q).every(l=>l.total===l.near+l.outbound+l.back+l.last&&l.carry===l.near+l.last&&l.detour>=0)"));
assert.ok(run("Math.min(...calculate(q).map(l=>l.total)) < calculate(q).sort((a,b)=>a.near-b.near)[0].total"));
const ids=[...js.matchAll(/\$\('([^']+)'\)/g)].map(m=>m[1]);
for(const id of new Set(ids)){if(!['copyPlan','resetExample'].includes(id))assert.ok(html.includes(`id="${id}"`),`missing #${id}`);}
console.log('PASS: 14 checks covering route accounting, size/time filtering, fee boundaries, validation, DOM references and scenario ranking.');
